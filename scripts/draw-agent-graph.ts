/**
 * Draw the assistant's LangGraph graph (lib/ai/agent.ts) as a Mermaid diagram.
 * Writes docs/agent-graph.md, which GitHub and VS Code's Markdown preview render as a picture.
 * Runs offline: no model call is made, and the API key isn't needed.
 *
 *   npm run agent:graph
 *
 * The nodes and arrows come from the compiled graph, and the details in each box come from the code and
 * config, so the drawing can't drift from what runs. LangGraph's own drawMermaid() is not used: it shows
 * "__start__"/"__end__", hard-codes pale colours that look wrong in dark mode, and leaves branch arrows unlabelled.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { getAgent } from "../lib/ai/agent";
import { CHANGE_TOOLS } from "../lib/ai/claim-guard";
import { AI_CONFIG } from "../lib/ai/config";
import { CACHEABLE } from "../lib/ai/loop-guard";
import { SCOPE_GUARD_SETTINGS } from "../lib/ai/scope-guard";
import { toolGroups, tools } from "../lib/ai/tools";

/** Lines shown under each node's name. A node missing here just shows its name. */
const NODE_NOTES: Record<string, string[]> = {
  guard: [
    `scope check · ${AI_CONFIG.scopeGuard ? "on" : "off (CHAT_SCOPE_GUARD)"}`,
    `effort ${SCOPE_GUARD_SETTINGS.effort} · last ${SCOPE_GUARD_SETTINGS.recentTurns} turns · fails open`,
  ],
  agent: [
    AI_CONFIG.model,
    `max ${AI_CONFIG.maxModelCallsPerTurn} model calls · ${AI_CONFIG.maxToolCallsPerTurn} tool calls`,
    `claim guard · checks ${CHANGE_TOOLS.size} change tools`,
  ],
  tools: [
    `${tools.length} tools in ${Object.keys(toolGroups).length} groups`,
    `loop guard · skips repeats of ${CACHEABLE.size} lookups`,
  ],
  finish: ["final reply with tools off", "pending calls answered not run"],
};

const START = "__start__";
const END = "__end__";
const code = (names: Iterable<string>) => [...names].map((n) => "`" + n + "`").join(", ");

/** Markdown under the diagram: every tool by group, and which ones each guard covers. */
function toolsSection() {
  return [
    `## Tools (${tools.length})`,
    "",
    "| Group | Count | Tools |",
    "| --- | --- | --- |",
    ...Object.entries(toolGroups).map(([group, list]) => `| ${group} | ${list.length} | ${code(list.map((t) => t.name))} |`),
    "",
    `- **Claim guard** checks replies against changes made by: ${code(CHANGE_TOOLS)}.`,
    `- **Loop guard** skips repeated calls to: ${code(CACHEABLE)}.`,
  ].join("\n");
}

async function main() {
  // Building the graph creates the chat model, which insists on a key. Nothing is sent, so a placeholder is fine.
  process.env.OPENROUTER_API_KEY ||= "not-needed-for-drawing";
  const graph = await getAgent().getGraphAsync();

  const lines = ["flowchart TD"];
  for (const id of Object.keys(graph.nodes)) {
    if (id === START) lines.push(`  ${START}([start]):::terminal`);
    else if (id === END) lines.push(`  ${END}([end]):::terminal`);
    else {
      const notes = (NODE_NOTES[id] ?? []).map((n) => `<br/><small>${n}</small>`).join("");
      lines.push(`  ${id}["<b>${id}</b>${notes}"]:::step`);
    }
  }
  // Solid arrows always run next; dotted ones are a router's choice, labelled with the branch name.
  for (const e of graph.edges) {
    const label = typeof e.data === "string" && e.data !== e.target ? e.data : "";
    if (e.conditional) lines.push(`  ${e.source} -.->${label ? `|${label}|` : ""} ${e.target}`);
    else lines.push(`  ${e.source} --> ${e.target}`);
  }
  // Mid-tone fills with dark text read on both light and dark backgrounds.
  lines.push(
    "  classDef step fill:#EEEDFE,stroke:#534AB7,color:#26215C",
    "  classDef terminal fill:#F1EFE8,stroke:#5F5E5A,color:#2C2C2A",
  );
  const mermaid = lines.join("\n");

  const out = "docs/agent-graph.md";
  mkdirSync("docs", { recursive: true });
  writeFileSync(
    out,
    [
      "# Assistant graph",
      "",
      "Generated by `npm run agent:graph` from `lib/ai/agent.ts`. Don't edit by hand.",
      "",
      "Solid arrows always run next. Dotted arrows are a choice the graph makes, labelled with the branch name. " +
        "The model and limits are read from the config and `.env` when the script runs.",
      "",
      "```mermaid",
      mermaid,
      "```",
      "",
      toolsSection(),
      "",
    ].join("\n"),
  );
  console.log(mermaid);
  console.log(`\nWrote ${out}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
