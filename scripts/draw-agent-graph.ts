/**
 * Draw the assistant's LangGraph graph (lib/ai/agent.ts) as a Mermaid diagram.
 * Writes docs/agent-graph.md, which GitHub and VS Code's Markdown preview render as a picture.
 * Runs offline: no model call is made, and the API key isn't needed.
 *
 *   npm run agent:graph
 *
 * The nodes and arrows come from the compiled graph, so the drawing can't drift from the code.
 * LangGraph's own drawMermaid() is not used: it shows "__start__"/"__end__", hard-codes pale colours
 * that look wrong in dark mode, and leaves branch arrows unlabelled.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { getAgent } from "../lib/ai/agent";

/** Shown under each node's name. A node missing here just shows its name. */
const NODE_NOTES: Record<string, string> = {
  guard: "scope check",
  agent: "model call + claim guard",
  tools: "store tools + loop guard",
  finish: "final reply, no tools",
};

const START = "__start__";
const END = "__end__";

async function main() {
  // Building the graph creates the chat model, which insists on a key. Nothing is sent, so a placeholder is fine.
  process.env.OPENROUTER_API_KEY ||= "not-needed-for-drawing";
  const graph = await getAgent().getGraphAsync();

  const lines = ["flowchart TD"];
  for (const id of Object.keys(graph.nodes)) {
    if (id === START) lines.push(`  ${START}([start]):::terminal`);
    else if (id === END) lines.push(`  ${END}([end]):::terminal`);
    else {
      const note = NODE_NOTES[id];
      lines.push(`  ${id}["<b>${id}</b>${note ? `<br/><small>${note}</small>` : ""}"]:::step`);
    }
  }
  // Solid arrows always run next; dotted ones are a router's choice, labelled with the branch name.
  for (const e of graph.edges) {
    const label = typeof e.data === "string" && e.data !== e.target ? e.data : "";
    if (e.conditional) lines.push(`  ${e.source} -.->${label ? `|${label}|` : ""} ${e.target}`);
    else lines.push(`  ${e.source} --> ${e.target}`);
  }
  // Mid-tone fills with dark or light text read on both light and dark backgrounds.
  lines.push(
    "  classDef step fill:#EEEDFE,stroke:#534AB7,color:#26215C",
    "  classDef terminal fill:#F1EFE8,stroke:#5F5E5A,color:#2C2C2A",
  );
  const mermaid = lines.join("\n");

  const out = "docs/agent-graph.md";
  mkdirSync("docs", { recursive: true });
  writeFileSync(
    out,
    "# Assistant graph\n\n" +
      "Generated by `npm run agent:graph` from `lib/ai/agent.ts`. Don't edit by hand.\n\n" +
      "Solid arrows always run next. Dotted arrows are a choice the graph makes, labelled with the branch name.\n\n" +
      `\`\`\`mermaid\n${mermaid}\n\`\`\`\n`,
  );
  console.log(mermaid);
  console.log(`\nWrote ${out}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
