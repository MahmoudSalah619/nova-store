/**
 * Draw the assistant's LangGraph graph (lib/ai/agent.ts) as a Mermaid diagram.
 * Writes docs/agent-graph.md, which GitHub and VS Code's Markdown preview render as a picture.
 * Runs offline: no model call is made, and the API key isn't needed.
 *
 *   npm run agent:graph
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { getAgent } from "../lib/ai/agent";

async function main() {
  // Building the graph creates the chat model, which insists on a key. Nothing is sent, so a placeholder is fine.
  process.env.OPENROUTER_API_KEY ||= "not-needed-for-drawing";
  const mermaid = (await getAgent().getGraphAsync()).drawMermaid();
  const out = "docs/agent-graph.md";

  mkdirSync("docs", { recursive: true });
  writeFileSync(
    out,
    `# Assistant graph\n\nGenerated by \`npm run agent:graph\` from \`lib/ai/agent.ts\`. Don't edit by hand.\n\n\`\`\`mermaid\n${mermaid}\n\`\`\`\n`,
  );
  console.log(mermaid);
  console.log(`\nWrote ${out}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
